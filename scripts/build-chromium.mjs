import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const files = ["offline.js", "offline-sprite-definitions.js"];
const sources = files.map((f) => readFileSync(`vendor/chromium/${f}`, "utf8"));
// Lexical platform dependencies keep upstream code unchanged and isolated per run.
const wrapper = `// Generated by scripts/build-chromium.mjs. Chromium BSD license: /vendor/chromium/LICENSE\nexport function createChromium(platform) {\nconst window = {devicePixelRatio:2,navigator:{userAgent:'Desktop'}};\nconst document = {querySelector:()=>({dir:'ltr'})};\nconst performance = {now:platform.now};\nconst Math = Object.create(globalThis.Math); Math.random = platform.random;\nconst loadTimeData = {valueExists:()=>false};\n${sources.join("\n")}\nreturn {Runner,Trex,Horizon,DistanceMeter,GameOverPanel,Obstacle,checkForCollision};\n}\n`;
writeFileSync("src/lib/chromium-engine.js", wrapper);
const paths = [
  ...files.map((f) => `vendor/chromium/${f}`),
  "src/lib/chromium-engine.js",
  "public/vendor/chromium/200-offline-sprite.png",
  "public/vendor/chromium/LICENSE",
];
writeFileSync(
  "vendor/chromium/manifest.json",
  JSON.stringify(
    {
      upstream: "https://github.com/chromium/chromium",
      revision: "0b0619d8287f51c4fca09d0385c163d30bd35c4b",
      tag: "98.0.4758.55",
      license: "BSD-3-Clause",
      modifications:
        "Source files unchanged. Generated lexical platform wrapper. Fly Dino supplies deterministic clock/randomness and replaces browser-page lifecycle hooks.",
      sha256: Object.fromEntries(
        paths.map((p) => [
          p,
          createHash("sha256").update(readFileSync(p)).digest("hex"),
        ]),
      ),
    },
    null,
    2,
  ) + "\n",
);
